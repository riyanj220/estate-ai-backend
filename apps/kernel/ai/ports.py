"""The typed AI ports. Text reaches a provider only as `RedactedText`.

Audio is the one exception: it cannot be redacted, goes to the speech port with no account data,
and is covered by the external-service notice (FR-32). A transcript is provider output: redact it
before it is sent to any port or stored.

`schema` is a structured-output schema generated by code (the registry), never from user input.
Adapters must honour `timeout` (seconds) and must not put provider bodies in exception text.
"""

from dataclasses import dataclass, field
from typing import Protocol

from apps.kernel.ai.redaction import RedactedText

ROLES = ("user", "assistant")


def require_redacted(*texts: object) -> None:
    if any(type(text) is not RedactedText for text in texts):
        raise TypeError("AI ports accept only RedactedText")


@dataclass(frozen=True)
class Message:
    role: str
    text: RedactedText

    def __post_init__(self) -> None:
        if self.role not in ROLES:
            raise ValueError("unknown role")
        require_redacted(self.text)


@dataclass(frozen=True)
class LLMRequest:
    """`system` is our instructions, `input` the user's text (what the input cap counts),
    `history` earlier turns and `context` retrieved passages (untrusted data, not instructions)."""

    system: RedactedText
    input: RedactedText
    history: tuple[Message, ...] = ()
    context: tuple[RedactedText, ...] = ()
    schema: dict | None = None

    def __post_init__(self) -> None:
        require_redacted(self.system, self.input, *self.context)
        if any(type(message) is not Message for message in self.history):
            raise TypeError("history holds Message values")

    def texts(self) -> tuple[RedactedText, ...]:
        return (self.system, *(m.text for m in self.history), *self.context, self.input)


@dataclass(frozen=True)
class LLMResponse:
    text: str = field(repr=False)


@dataclass(frozen=True)
class Audio:
    data: bytes = field(repr=False)
    content_type: str


class LLMPort(Protocol):
    provider: str
    model: str

    def complete(self, request: LLMRequest, *, timeout: float) -> LLMResponse: ...


class EmbeddingsPort(Protocol):
    provider: str
    model: str

    def embed(self, texts: tuple[RedactedText, ...], *, timeout: float) -> list[list[float]]: ...


class SpeechPort(Protocol):
    provider: str
    model: str

    def transcribe(self, audio: Audio, *, timeout: float) -> str: ...
